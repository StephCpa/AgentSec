"""Advance the public generator alongside real calls and check R1--R4.

Observation callbacks compare already-generated bytes with the real event, then
read selected real relational state diagnostically. No real state is passed to
the generator. This is finite boundary checking, not an inductive proof.
"""
import hashlib
import json
from pathlib import Path
from unittest.mock import patch

from constructive_trace import RecordingRuntime, FixtureSigningOracle
from mixed_delegated_ledger import parse_mixed_action
from public_gateway import parse_request, PublicGatewayLedger
from public_simulator import PublicSimulator
from public_trace_adapter import PublicTraceAdapter
from restricted_trace import PLANS, run_plan
from state_relation import assert_state_relation, digest


class ObservedRecords(list):
    def __init__(self, observer):
        super().__init__()
        self.observer = observer

    def append(self, event):
        self.observer(event)
        super().append(event)


class StepwiseRuntime(RecordingRuntime):
    def __init__(self, *args, ancestor_expiries=None, **kwargs):
        expiries = {} if ancestor_expiries is None else dict(ancestor_expiries)
        install_key = PublicGatewayLedger.install_key
        def install(ledger, tenant, kid, actor, role, public_key, not_before=0, expires_at=2**62):
            return install_key(ledger, tenant, kid, actor, role, public_key, not_before, expiries.get(kid, expires_at))
        # Change fixture bootstrap, never mutate an enrolled key in storage.
        with patch.object(PublicGatewayLedger, 'install_key', new=install):
            super().__init__(*args, **kwargs)
        for kid, expiry in expiries.items():
            self.cfg['keys'][kid]['expires_at'] = expiry
        self.signer = FixtureSigningOracle()
        self.simulator = PublicSimulator(self.cfg, {}, self.signer)
        self.checkpoints = [dict(index=0, kind='INITIAL', relation=assert_state_relation(self, self.simulator.state))]
        self.records = ObservedRecords(self._observe)

    def _observe(self, actual):
        command = self.commands[len(self.simulator.records)]
        if command['kind'] == 'PUBLIC':
            request = parse_request(bytes.fromhex(command['request']))
            if request['method'] == 'SUBMIT':
                action = parse_mixed_action(request['payload']['action'])
                # Public test target and operation shape; never actual results.
                width = action['bucket_count'] if action['operation_kind'] == 'histogram' else 1
                self.simulator.state.oracle.setdefault(action['operation'], (self.target,) + (0,) * (width - 1))
        with patch('sqlite3.connect', side_effect=AssertionError('generator DB access')), \
             patch.object(PublicGatewayLedger, 'handle_public', side_effect=AssertionError('generator runtime access')), \
             patch.object(PublicTraceAdapter, '_public', side_effect=AssertionError('generator observed response access')):
            generated = self.simulator.emit(command)
        if generated != actual:
            raise AssertionError('event differs at ' + str(len(self.records)))
        relation = assert_state_relation(self, self.simulator.state)
        self.checkpoints.append(dict(index=len(self.simulator.records), kind=command['kind'], relation=relation))


def run_stepwise(plan, mask=3, target=1):
    if type(target) is not int or not 0 <= target <= 3:
        raise ValueError('output outside public capacity')
    instances = []
    def create(*args, **kwargs):
        runtime = StepwiseRuntime(*args, target=target, **kwargs)
        instances.append(runtime)
        return runtime
    with patch('restricted_trace.Runtime', side_effect=create):
        result = run_plan(plan, mask)
    result['checkpoints'] = instances[0].checkpoints
    result['target'] = target
    return result


def main():
    import argparse
    import gzip
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists():
        parser.error('output exists')
    args.output.mkdir(parents=True)
    groups = [(plan, 1) for plan in PLANS] + [(plan, target) for target in (0, 2, 3) for plan in ('normal', 'adaptive')]
    report = dict(profile='restricted-stepwise-state-relation-v1', passed=False,
                  source_sha256={p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in Path(__file__).parent.glob('*.py')},
                  scope='Finite R1-R4 checks after completed public events, not crash-point checks or universal induction.', cases=[])
    checkpoints = []
    for plan, target in groups:
        reference = None
        for mask in range(8):
            result = run_stepwise(plan, mask, target)
            trace = json.dumps(result['records'], sort_keys=True, separators=(',', ':')).encode()
            signature = (hashlib.sha256(trace).hexdigest(), digest(result['checkpoints']))
            if reference is not None and signature != reference:
                raise AssertionError('conditioned trace or state relation differs')
            reference = signature
            report['cases'].append(dict(plan=plan, target=target, mask=mask, records=len(result['records']),
                checkpoints=len(result['checkpoints']), trace_sha256=signature[0], checkpoint_sha256=signature[1]))
            checkpoints.append(dict(plan=plan, target=target, mask=mask, checkpoints=result['checkpoints']))
        print('PASS', plan, 'target', target, '8 inputs', flush=True)
    report.update(passed=True, cases_count=len(report['cases']), checkpoint_count=sum(case['checkpoints'] for case in report['cases']),
                  directed_neighbor_comparisons=24 * len(groups))
    (args.output / 'summary.json').write_text(json.dumps(report, indent=2) + '\n')
    with (args.output / 'checkpoints.json.gz').open('wb') as stream:
        with gzip.GzipFile(fileobj=stream, mode='wb', mtime=0) as compressed:
            compressed.write(json.dumps(checkpoints, separators=(',', ':')).encode())


if __name__ == '__main__':
    main()
